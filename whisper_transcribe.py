#!/usr/bin/env python3
"""whisper-transcribe: guided local transcription.

Run it with no arguments, in the folder that holds the audio file.
The program reads the files that already exist there and tells you the next step.

File names show the stage:

  <name> (review).txt.bck      copy of the transcript before review. Do not edit.
  <name> (review).srt.bck      copy of the subtitles before review. Gives the timing.
  <name> (review).txt          the transcript you correct by hand (only while reviewing).
  <name> (review).srt          the automatic subtitles, to compare with the audio.
  <name> (review).mp4          video with the audio and the automatic subtitles.
  <name>.txt                   official transcript: the reviewed text, once confirmed.
  <name>.srt                   official subtitles: made from the reviewed text.
  <name>.mp4                   official video with the subtitles burned in.
  <name>.sha256                plain-text record of hashes and the steps that were run.

The steps, decided by the files and by the record:

  1. No "<name> (review).txt.bck" yet: transcribe. Creates the backups, the working
     transcript and the review video.
  2. No "subtitles" entry in "<name>.sha256" yet, or "(review).txt" exists: review.
     You correct "(review).txt" by hand. When you run again, the program shows what
     changed and asks you to confirm. Then "(review).txt" becomes "<name>.txt" and
     the official subtitles are written.
  3. Official files exist and nothing is pending: done. You can reopen the review to
     correct the text again; that copies the official transcript back to "(review).txt".
"""

import argparse
import datetime
import os
import shutil
import sys

import apply_review
import provenance
import render_video
import transcribe_audio
from progress import Monitor

HERE = os.path.dirname(os.path.abspath(__file__))
AUDIO_EXTENSIONS = (".m4a", ".mp3", ".wav", ".ogg", ".opus", ".aac", ".flac")
SHOW_CHANGES = 40


# ----------------------------------------------------------------- helpers

def hms(seconds):
    return str(datetime.timedelta(seconds=int(seconds)))


def srt_time(seconds):
    ms = int(round(seconds * 1000))
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def ask(question, default=False):
    suffix = "[Y/n]" if default else "[y/N]"
    answer = input(f"{question} {suffix} ").strip().lower()
    if not answer:
        return default
    return answer in ("y", "yes")


def list_audio(folder):
    return sorted(
        os.path.join(folder, f) for f in os.listdir(folder)
        if os.path.isfile(os.path.join(folder, f)) and f.lower().endswith(AUDIO_EXTENSIONS)
    )


def paths_for(audio):
    base = os.path.splitext(audio)[0]
    return {
        "base": base,
        "txt_raw": base + " (review).txt.bck",
        "srt_raw": base + " (review).srt.bck",
        "txt_review": base + " (review).txt",
        "srt_review": base + " (review).srt",
        "video_review": base + " (review).mp4",
        "txt": base + ".txt",
        "srt": base + ".srt",
        "video": base + ".mp4",
    }


def show_files(paths, keys):
    for key in keys:
        p = paths[key]
        if os.path.exists(p):
            print(f"  {os.path.basename(p)}")


def stop(message):
    print(message)
    sys.exit(1)


def write_transcript_files(p, audio, segments, model_name, info):
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    with open(p["txt_raw"], "w", encoding="utf-8") as f:
        f.write(f"TRANSCRIPT: {os.path.basename(audio)}\n")
        f.write(f"Model: {model_name}   Language: {info['language']}   Created: {now}\n")
        f.write("Automatic transcript. Do not edit this file; edit the (review) file.\n")
        f.write("=" * 70 + "\n\n")
        for start, _, text in segments:
            f.write(f"[{hms(start)}] {text}\n")
    with open(p["srt_raw"], "w", encoding="utf-8") as f:
        for n, (start, end, text) in enumerate(segments, 1):
            f.write(f"{n}\n{srt_time(start)} --> {srt_time(end)}\n{text}\n\n")
    shutil.copyfile(p["txt_raw"], p["txt_review"])
    shutil.copyfile(p["srt_raw"], p["srt_review"])


# -------------------------------------------------------------- step 1

def choose_model(cli_model):
    if cli_model:
        return cli_model
    print("Choose the model (press Enter for the default):")
    for i, (name, desc) in enumerate(transcribe_audio.MODELS.items(), 1):
        mark = " (default)" if name == transcribe_audio.DEFAULT_MODEL else ""
        print(f"  {i}) {name}{mark}: {desc}")
    answer = input("Your choice [1]: ").strip()
    if not answer:
        return transcribe_audio.DEFAULT_MODEL
    if answer.isdigit() and 1 <= int(answer) <= len(transcribe_audio.MODELS):
        return list(transcribe_audio.MODELS)[int(answer) - 1]
    if answer in transcribe_audio.MODELS:
        return answer
    stop(f"Unknown model: {answer}")


def step_transcribe(audio, p, args):
    print(f"Audio: {os.path.basename(audio)}")
    model_name = choose_model(args.model)
    monitor = Monitor()
    segments, info = transcribe_audio.transcribe_audio(audio, model_name, args.language, monitor)
    if not segments:
        monitor.close()
        stop("No speech was found in this audio. Nothing was written.")

    monitor.begin_step(4, 5, "Writing files", bar=False)
    write_transcript_files(p, audio, segments, model_name, info)
    provenance.append_event(
        p["base"], "transcribed",
        audio_sha256=provenance.file_sha256(audio),
        model=model_name,
        language=info["language"],
        device=info["device"],
        compute=info["compute_type"],
        faster_whisper=_library_version(),
        program=provenance.tool_version(HERE),
    )

    monitor.end_step()
    monitor.begin_step(5, 5, "Review video", bar=True)
    render_video.render_video(audio, p["video_review"], subtitles_path=p["srt_raw"],
                              on_progress=monitor.progress)
    monitor.end_step()
    monitor.close()
    provenance.append_event(p["base"], "review-video",
                            file=os.path.basename(p["video_review"]),
                            sha256=provenance.file_sha256(p["video_review"]))

    print(f"\nTranscript created: {len(segments)} segments.")
    show_files(p, ["txt_raw", "srt_raw", "txt_review", "srt_review", "video_review"])
    print("\nNEXT STEP: review the transcript.")
    print(f"  1. Open {os.path.basename(p['txt_review'])} and {os.path.basename(p['video_review'])}"
          " (the video shows the automatic subtitles).")
    print("  2. Correct the text while you listen. Keep the [h:mm:ss] at the start of each line.")
    print("  3. Mark what you cannot understand as ___ instead of guessing.")
    print(f"  4. Do not edit {os.path.basename(p['txt_raw'])}: it is the untouched automatic version.")
    print("  5. Run whisper-transcribe again in this folder.")


def _library_version():
    try:
        from importlib.metadata import version
        return version("faster-whisper")
    except Exception:
        return "unknown"


# -------------------------------------------------------------- step 2

def show_changes(removed, added):
    by_time = {}
    for seconds, text in removed:
        by_time.setdefault(seconds, [[], []])[0].append(text)
    for seconds, text in added:
        by_time.setdefault(seconds, [[], []])[1].append(text)
    shown = 0
    for seconds in sorted(by_time):
        if shown >= SHOW_CHANGES:
            break
        old, new = by_time[seconds]
        for text in old:
            print(f"  - [{hms(seconds)}] {text}")
        for text in new:
            print(f"  + [{hms(seconds)}] {text}")
        shown += 1
    if shown < len(by_time):
        print(f"  ... and {len(by_time) - shown} more")


def make_official(p, unchanged_confirmed, removed, added):
    """Turn the confirmed (review) transcript into the official files."""
    raw_segments = apply_review.read_srt(p["srt_raw"])
    reviewed = apply_review.read_transcript(p["txt_review"])
    joined, unmatched = apply_review.join(raw_segments, reviewed)
    apply_review.write_srt(joined, p["srt"])
    txt_hash = provenance.file_sha256(p["txt_review"])
    os.replace(p["txt_review"], p["txt"])
    print(f"\nOfficial: {os.path.basename(p['txt'])} and {os.path.basename(p['srt'])} "
          f"({len(joined)} subtitle segments). The (review) copy was removed.")

    if unmatched:
        print(f"\nWARNING: {len(unmatched)} reviewed line(s) matched no subtitle segment and were NOT used:")
        for seconds, text in unmatched[:SHOW_CHANGES]:
            print(f"  [{hms(seconds)}] {text}")
        print("Check that their [h:mm:ss] was not changed.")

    provenance.append_event(
        p["base"], "subtitles",
        txt_sha256=txt_hash,
        srt_sha256=provenance.file_sha256(p["srt"]),
        changed_lines=len(removed) + len(added),
        unchanged_confirmed="yes" if unchanged_confirmed else "no",
        unmatched=len(unmatched),
    )


def step_review(audio, p, args):
    print(f"Audio: {os.path.basename(audio)}")
    if not os.path.exists(p["txt_review"]):
        shutil.copyfile(p["txt_raw"], p["txt_review"])
        print(f"Recreated {os.path.basename(p['txt_review'])} from the automatic copy.")

    recorded_audio = provenance.last_value(p["base"], "transcribed", "audio_sha256")
    if recorded_audio and provenance.file_sha256(audio) != recorded_audio:
        print("WARNING: this audio file is not the one that was transcribed (the hash differs).")
        if not ask("Continue anyway?"):
            stop("Stopped. Nothing was changed.")

    removed, added = apply_review.changed_lines(p["txt_raw"], p["txt_review"])
    review_name = os.path.basename(p["txt_review"])
    if not removed and not added:
        print(f"{review_name} is identical to the automatic transcript.")
        print("If you reviewed it and nothing needs to change, confirm that it is official as it is.")
        if not ask("Confirm that the automatic transcript is official?"):
            stop(f"Nothing done. Edit {review_name} and run again.")
        unchanged = True
    else:
        print(f"Changes in {review_name} compared with the automatic transcript:")
        show_changes(removed, added)
        print(f"  {len(removed)} line(s) removed or changed, {len(added)} line(s) added or changed.")
        if not ask("Confirm these changes and create the official files?"):
            stop("Nothing done.")
        unchanged = False

    make_official(p, unchanged, removed, added)

    if ask("Render the video with the subtitles burned in now?", default=True):
        step_video(audio, p)
    else:
        print("Later, run whisper-transcribe again to render the video.")


# -------------------------------------------------------------- step 3

def step_video(audio, p):
    monitor = Monitor()
    monitor.begin_step(1, 1, "Rendering video", bar=True)
    render_video.render_video(audio, p["video"], subtitles_path=p["srt"], on_progress=monitor.progress)
    monitor.end_step()
    monitor.close()
    provenance.append_event(p["base"], "video-subtitled",
                            file=os.path.basename(p["video"]),
                            sha256=provenance.file_sha256(p["video"]))
    print(f"Video: {os.path.basename(p['video'])}")


def reopen(p):
    shutil.copyfile(p["txt"], p["txt_review"])
    provenance.append_event(p["base"], "reopened", file=os.path.basename(p["txt_review"]))
    print(f"Reopened: {os.path.basename(p['txt_review'])} is a copy of the official transcript.")
    print("Correct it, then run whisper-transcribe again. The official files will be updated.")


def step_done(audio, p, args):
    print(f"Audio: {os.path.basename(audio)}")
    official_hash = provenance.file_sha256(p["txt"])
    recorded_hash = provenance.last_value(p["base"], "subtitles", "txt_sha256")
    if official_hash != recorded_hash:
        print(f"{os.path.basename(p['txt'])} was changed by hand after it was confirmed.")
        if ask("Reopen the review to correct it through the program?"):
            reopen(p)
            return
        stop("Nothing done. The official files were left as they are.")

    if not os.path.exists(p["video"]):
        print("The official subtitles are up to date, but the video does not exist yet.")
        if ask("Render it now?", default=True):
            step_video(audio, p)
    else:
        print("Everything is done for this audio:")
        show_files(p, ["txt", "srt", "video"])

    if ask("Reopen the review to correct the text?"):
        reopen(p)


# -------------------------------------------------------------- main

def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except AttributeError:
        pass

    parser = argparse.ArgumentParser(
        prog="whisper-transcribe",
        description="Guided local transcription. Run it in the folder that holds the audio file.")
    parser.add_argument("--audio", help="audio file to use, if the folder has more than one")
    parser.add_argument("--model", help=f"skip the model question: {', '.join(transcribe_audio.MODELS)}")
    parser.add_argument("--language", default="es", help="spoken language code (default: es)")
    args = parser.parse_args()

    if args.audio:
        audio = os.path.abspath(args.audio)
        if not os.path.isfile(audio):
            stop(f"No such file: {args.audio}")
    else:
        audios = list_audio(os.getcwd())
        if not audios:
            stop("No audio file in this folder. Copy or move the recording here and run again.\n"
                 f"Supported: {', '.join(AUDIO_EXTENSIONS)}")
        if len(audios) == 1:
            audio = audios[0]
        else:
            print("More than one audio file in this folder:")
            for i, a in enumerate(audios, 1):
                print(f"  {i}) {os.path.basename(a)}")
            answer = input("Which one? Enter its number: ").strip()
            if not (answer.isdigit() and 1 <= int(answer) <= len(audios)):
                stop("Nothing done.")
            audio = audios[int(answer) - 1]

    p = paths_for(audio)
    try:
        if not os.path.exists(p["txt_raw"]):
            step_transcribe(audio, p, args)
        elif not os.path.exists(p["srt_raw"]):
            stop(f"Broken state: {os.path.basename(p['txt_raw'])} exists but "
                 f"{os.path.basename(p['srt_raw'])} does not. Move the audio's files aside and start again.")
        elif (provenance.last_value(p["base"], "subtitles", "txt_sha256") is None
              or os.path.exists(p["txt_review"])):
            step_review(audio, p, args)
        else:
            step_done(audio, p, args)
    except KeyboardInterrupt:
        stop("\nInterrupted. Files already written were kept; run again to continue.")


if __name__ == "__main__":
    main()
